def icon(name, x, y, size=24, col="#ffffff", sw=1.7, op=1.0, extra=""):
    """Place a glyph with its top-left at (x, y), scaled to `size`."""
    body, mode = I[name]
    body = body.replace("currentColor", col)
    k = size / 24.0
    if mode == "f":
        g = '<g fill="%s" stroke="none">%s</g>' % (col, body)
    else:
        g = ('<g fill="none" stroke="%s" stroke-width="%.2f" stroke-linecap="round" '
             'stroke-linejoin="round">%s</g>' % (col, sw, body))
    return ('<g transform="translate(%s,%s) scale(%.4f)" opacity="%s"%s>%s</g>'
            % (x, y, k, op, extra, g))
